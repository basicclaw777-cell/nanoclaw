#!/usr/bin/env node
/**
 * refresh-dashboard.js — Reads ops-agent JSON outputs + system state,
 * injects them as inline JS data into command-centre/index.html.
 *
 * Runs: PM2 cron every 6 hours, or manually before opening dashboard.
 * No server needed — just file reads → HTML rewrite.
 * ESM module.
 */

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { execSync } from 'child_process';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const HOME = process.env.HOME;
const OPS_REPORTS = path.join(HOME, 'nanoclaw', 'ops-agent', 'reports');
const OPS_CONFIG = path.join(HOME, 'nanoclaw', 'ops-agent', 'ops-config.json');
const MEMBER_DATA = path.join(HOME, 'br-gm-agent', 'reports', 'member-data.json');
const HTML_PATH = path.join(__dirname, 'index.html');
const DATA_PATH = path.join(__dirname, 'dashboard-data.js');

function readJSON(filepath) {
  try { return JSON.parse(fs.readFileSync(filepath, 'utf-8')); }
  catch { return null; }
}

function getLatestReport(prefix) {
  if (!fs.existsSync(OPS_REPORTS)) return null;
  const files = fs.readdirSync(OPS_REPORTS)
    .filter(f => f.startsWith(prefix) && f.endsWith('.json'))
    .sort()
    .reverse();
  return files.length > 0 ? readJSON(path.join(OPS_REPORTS, files[0])) : null;
}

function getPM2Status() {
  try {
    const raw = execSync('pm2 jlist', { timeout: 10000 }).toString();
    const procs = JSON.parse(raw);
    return {
      online: procs.filter(p => p.pm2_env?.status === 'online').length,
      stopped: procs.filter(p => p.pm2_env?.status === 'stopped').length,
      total: procs.length,
      critical: ['cathedral-bot', 'cath-bridge', 'vault-watcher', 'sentinel'].map(name => {
        const p = procs.find(pr => pr.name === name);
        return { name, status: p?.pm2_env?.status || 'missing' };
      }),
    };
  } catch { return { online: 0, stopped: 0, total: 0, critical: [] }; }
}

// Build data object
const pnl = getLatestReport('pnl');
const commission = getLatestReport('commission');
const opsConfig = readJSON(OPS_CONFIG);
const memberData = readJSON(MEMBER_DATA);
const pm2 = getPM2Status();

// MPF — inline since we can't await at top level easily in this context
let mpf = null;
try {
  const config = readJSON(OPS_CONFIG) || {};
  const mpfConfig = config.mpf || {};
  const now = new Date();
  const year = now.getMonth() === 11 ? now.getFullYear() + 1 : now.getFullYear();
  const month = (now.getMonth() + 1) % 12 + 1;
  const deadline = `${year}-${String(month).padStart(2, '0')}-10`;
  const daysLeft = Math.ceil((new Date(deadline) - now) / 86400000);
  mpf = { nextDeadline: deadline, daysUntilDeadline: daysLeft, alerts: mpfConfig.staff?.length === 0 ? 1 : 0 };
} catch {}

// HR calendar
let hrAlerts = 0;
try {
  const config = readJSON(OPS_CONFIG) || {};
  const hr = config.hr || {};
  if (hr.insuranceRenewalDate) {
    const days = Math.ceil((new Date(hr.insuranceRenewalDate) - new Date()) / 86400000);
    if (days <= 30) hrAlerts++;
  }
  for (const d of (hr.deadlines || [])) {
    const days = Math.ceil((new Date(d.date) - new Date()) / 86400000);
    if (days <= 30) hrAlerts++;
  }
} catch {}

// Workstream status
const workstreams = [
  { phase: 0, name: 'Curriculum', desc: '10-Block system documented + config wired', status: 'done', icon: '📖' },
  { phase: 1, name: 'Operations', desc: 'Finance, HR, compliance, scheduling', status: 'done', icon: '⚙️' },
  { phase: 2, name: 'Dashboard', desc: 'KPI dashboard + command centre', status: 'active', icon: '📊' },
  { phase: 3, name: 'Client Comms', desc: 'WhatsApp templates, comms queue, approval gate', status: 'planned', icon: '💬' },
  { phase: 4, name: 'Growth + Maya', desc: 'Content pipeline, social voice, IG strategy', status: 'planned', icon: '🚀' },
  { phase: 5, name: 'Merch Agent', desc: 'Design, sourcing, inventory, milestone rewards', status: 'planned', icon: '👕' },
];

const dashboardData = {
  refreshed: new Date().toISOString(),
  pnl,
  commission,
  memberSummary: memberData ? {
    total: memberData.total_active_members,
    churnRiskMedium: memberData.summary?.churn_risk_medium || 0,
    churnRiskHigh: memberData.summary?.churn_risk_high || 0,
    expiringSoon: memberData.summary?.expiring_soon || 0,
    dataAsOf: memberData.export_date,
  } : null,
  pm2,
  mpf,
  hrAlerts,
  workstreams,
  peakRevenue: 933030,
  currentAnnualised: pnl ? pnl.revenue.totalEstimate * 12 : 0,
  lapsedMembers: 566,
};

// Write as JS module that HTML can load via <script>
const jsContent = `// Auto-generated by refresh-dashboard.js — ${new Date().toISOString()}
// Do not edit manually. Run: node command-centre/refresh-dashboard.js
const DASHBOARD_DATA = ${JSON.stringify(dashboardData, null, 2)};
`;

fs.writeFileSync(DATA_PATH, jsContent);
console.log(`Dashboard data refreshed → ${DATA_PATH}`);
console.log(`  P&L: ${pnl ? pnl.month : 'none'}`);
console.log(`  Members: ${memberData?.total_active_members || '?'}`);
console.log(`  PM2: ${pm2.online}↑ ${pm2.stopped}↓`);
